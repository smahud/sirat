#!/usr/bin/env bash
# SIRAT — Install/Deploy script (native, no Docker) di VPS Debian.
# Dipanggil sebagai root di VPS: bash /var/www/sirat/scripts/vps-install.sh
# Asumsi: source code sudah di-sync ke /var/www/sirat/, .env sudah diisi.
set -euo pipefail

WWW=/var/www/sirat
ARCHIVE_ROOT=/var/lib/sirat/archive
STAGING_ROOT=/var/lib/sirat/staging
LOG_DIR=/var/log/sirat
PORT=3901

say() { echo -e "\n== $1 =="; }
fail() { echo "ERROR: $1" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || fail "Jalankan sebagai root"
[ -d "$WWW/prisma" ] || fail "$WWW/prisma tidak ditemukan — sync source dulu"

say "1. Install PostgreSQL 15 (bila belum)"
if ! command -v psql >/dev/null 2>&1; then
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq postgresql postgresql-contrib
  systemctl enable --now postgresql
fi
psql --version

say "2. Buat user sistem sirat (bila belum)"
if ! id sirat >/dev/null 2>&1; then
  useradd --system --no-create-home --shell /usr/sbin/nologin \
    --home-dir "$WWW" sirat
fi
id sirat

say "3. Buat direktori storage + log"
mkdir -p "$ARCHIVE_ROOT" "$STAGING_ROOT" "$LOG_DIR"
chown -R sirat:sirat /var/lib/sirat /var/log/sirat
chmod 0750 /var/lib/sirat /var/log/sirat

say "4. Buat DB + role PostgreSQL (idempotent)"
DB_NAME="${SIRAT_DB_NAME:-sirat}"
DB_USER="${SIRAT_DB_USER:-sirat}"
DB_PASS="${SIRAT_DB_PASSWORD:-$(openssl rand -base64 24 | tr -d '/+=' | head -c 24)}"
# sudo -u postgres dari /tmp agar tidak access /root
cd /tmp
sudo -u postgres psql -tc "SELECT 1 FROM pg_roles WHERE rolname='$DB_USER'" | grep -q 1 \
  || sudo -u postgres psql -c "CREATE ROLE $DB_USER WITH LOGIN PASSWORD '$DB_PASS';"
sudo -u postgres psql -tc "SELECT 1 FROM pg_database WHERE datname='$DB_NAME'" | grep -q 1 \
  || sudo -u postgres createdb --owner=$DB_USER --encoding=UTF8 "$DB_NAME"
sudo -u postgres psql -c "ALTER ROLE $DB_USER WITH LOGIN PASSWORD '$DB_PASS';" >/dev/null
echo "DB_USER=$DB_USER DB_NAME=$DB_NAME (password disimpan ke /etc/sirat-db-credential)"

# Pastikan PostgreSQL listen hanya localhost (Blueprint §16.5)
PG_CONF=$(find /etc/postgresql -name postgresql.conf | head -1)
if [ -n "$PG_CONF" ] && ! grep -q "^listen_addresses = 'localhost'" "$PG_CONF"; then
  if grep -q "^#listen_addresses" "$PG_CONF"; then
    sed -i "s/^#listen_addresses.*/listen_addresses = 'localhost'/" "$PG_CONF"
  else
    echo "listen_addresses = 'localhost'" >> "$PG_CONF"
  fi
  systemctl reload postgresql
fi

# Simpan credential ke file 0600 untuk referensi
install -m 0600 /dev/null /etc/sirat-db-credential
cat > /etc/sirat-db-credential <<EOF
# SIRAT DB credential — generated by vps-install.sh
# Hanya untuk root; jangan commit ke repo
DB_NAME=$DB_NAME
DB_USER=$DB_USER
DB_PASS=$DB_PASS
DATABASE_URL=postgresql://$DB_USER:$DB_PASS@127.0.0.1:5432/$DB_NAME?schema=public
EOF
chmod 0600 /etc/sirat-db-credential

say "5. Update .env di $WWW"
# Inject DATABASE_URL bila kosong
if [ ! -f "$WWW/.env" ]; then
  cp "$WWW/.env.example" "$WWW/.env"
fi
if ! grep -q "^DATABASE_URL=" "$WWW/.env" || grep -q "^DATABASE_URL=.*CHANGE_ME" "$WWW/.env"; then
  # Replace atau append
  sed -i "s|^DATABASE_URL=.*|DATABASE_URL=postgresql://$DB_USER:$DB_PASS@127.0.0.1:5432/$DB_NAME?schema=public|" "$WWW/.env"
  grep -q "^DATABASE_URL=" "$WWW/.env" \
    || echo "DATABASE_URL=postgresql://$DB_USER:$DB_PASS@127.0.0.1:5432/$DB_NAME?schema=public" >> "$WWW/.env"
fi
# Generate SESSION_SECRET bila masih placeholder
if ! grep -q "^SESSION_SECRET=.*CHANGE_ME" "$WWW/.env" && grep -q "^SESSION_SECRET=CHANGE_ME" "$WWW/.env"; then
  SECRET=$(openssl rand -base64 48 | tr -d '\n')
  sed -i "s|^SESSION_SECRET=.*|SESSION_SECRET=$SECRET|" "$WWW/.env"
fi
chmod 0600 "$WWW/.env"
chown sirat:sirat "$WWW/.env"
echo "DATABASE_URL dan SESSION_SECRET sudah diset."

say "6. Install npm dependencies + prisma generate"
cd "$WWW"
# --legacy-peer-deps: vitest@5 minta @types/node ^22 tapi kita pakai 20 (runtime Node 20).
# Tidak bermasalah karena vitest hanya dev dep; runtime prod tidak menggunakannya.
npm ci --no-audit --no-fund --legacy-peer-deps
npx prisma generate --schema prisma/schema.prisma

say "7. Push schema ke PostgreSQL (db push untuk initial deploy; migration sesudahnya)"
npx prisma db push --schema prisma/schema.prisma --accept-data-loss --skip-generate
echo "Skema PostgreSQL siap."

say "8. Build Next.js standalone"
npm run build
# Pastikan static + public tersalin (lihat package.json build script)
ls .next/standalone/.next/static >/dev/null
ls .next/standalone/public >/dev/null
echo "Build standalone OK."

say "9. Seed preset + bootstrap admin"
SIRAT_ADMIN_USERNAME="${SIRAT_ADMIN_USERNAME:-admin}"
# Generate password admin bila tidak diset via env
ADMIN_PASS="${SIRAT_ADMIN_PASSWORD:-$(openssl rand -base64 18 | tr -d '/+=')}"
SIRAT_ADMIN_USERNAME="$SIRAT_ADMIN_USERNAME" \
SIRAT_ADMIN_PASSWORD="$ADMIN_PASS" \
node scripts/bootstrap-admin.mjs || true

# Seed (idempotent — lihat scripts/seed.mjs upsert)
node scripts/seed.mjs

# Catat admin credential
cat > /etc/sirat-admin-credential <<EOF
# SIRAT admin bootstrap — generated by vps-install.sh
# Hanya untuk root; ganti password setelah login pertama.
USERNAME=$SIRAT_ADMIN_USERNAME
PASSWORD=$ADMIN_PASS
EOF
chmod 0600 /etc/sirat-admin-credential
echo "============================================"
echo "ADMIN USERNAME: $SIRAT_ADMIN_USERNAME"
echo "ADMIN PASSWORD: $ADMIN_PASS  (juga di /etc/sirat-admin-credential)"
echo "Ganti password setelah login pertama via /api/users/me/password"
echo "============================================"

say "10. Set ownership + permission"
chown -R sirat:sirat "$WWW/.next" "$WWW/public"
# .next/standalone harus readable oleh sirat
find "$WWW/.next/standalone" -type d -exec chmod 0755 {} \;

say "11. Install systemd unit"
cat > /etc/systemd/system/sirat.service <<EOF
[Unit]
Description=SIRAT - Sistem Informasi Registrasi & Arsip Surat
Documentation=file:///var/www/sirat/docs/RUNBOOK.md
After=network-online.target postgresql.service
Wants=network-online.target
Requires=postgresql.service

[Service]
Type=simple
User=sirat
Group=sirat
WorkingDirectory=/var/www/sirat/.next/standalone
EnvironmentFile=/var/www/sirat/.env
Environment=NODE_ENV=production
Environment=PORT=$PORT
Environment=HOSTNAME=0.0.0.0
ExecStart=/usr/bin/node server.js
Restart=on-failure
RestartSec=5s
TimeoutStopSec=15s
StandardOutput=journal
StandardError=journal
SyslogIdentifier=sirat
# Hardening
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths=/var/lib/sirat /var/log/sirat /var/www/sirat/.next/standalone
PrivateTmp=true
PrivateDevices=true
ProtectKernelTunables=true
ProtectControlGroups=true
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
RestrictNamespaces=true
LockPersonality=true
MemoryDenyWriteExecute=false
RestrictRealtime=true
RestrictSUIDSGID=true

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable sirat
systemctl restart sirat
sleep 2
systemctl --no-pager --full status sirat | head -20

say "12. Smoke test localhost:$PORT"
sleep 2
curl -sS -o /dev/null -w "GET /api/auth/me -> HTTP %{http_code} (expect 401)\n" http://127.0.0.1:$PORT/api/auth/me
curl -sS http://127.0.0.1:$PORT/api/auth/me | head -c 200
echo

say "13. Disk usage + port check"
ss -tlnp | grep ":$PORT " || fail "Port $PORT tidak listen"
df -h /var/lib/sirat /var/www/sirat | head -5

echo ""
echo "============================================================"
echo "✅ SIRAT terpasang di port $PORT"
echo "============================================================"
echo "Lokasi       : /var/www/sirat"
echo "Archive root : $ARCHIVE_ROOT"
echo "DB credential: /etc/sirat-db-credential  (chmod 0600, root only)"
echo "Admin cred   : /etc/sirat-admin-credential (chmod 0600, root only)"
echo "Log          : journalctl -u sirat -f"
echo ""
echo "LANGKAH BERIKUTNYA:"
echo "  1. Konfigurasi reverse proxy (LiteSpeed vhost) untuk"
echo "     sirat.yapsidarussalam.or.id → http://127.0.0.1:$PORT"
echo "  2. Test login via browser: https://sirat.yapsidarussalam.or.id"
echo "  3. Login admin, ganti password, buat unit/profil aktif."
echo "  4. Lihat docs/RUNBOOK.md untuk operasional harian."
